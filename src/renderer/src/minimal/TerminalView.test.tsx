it('blocks command-mode typing but forwards native device replies, and preserves the emulator on exit', async () => {
  const { props, transport, view } = setup()
  await waitFor(() => expect(transport.attach).toHaveBeenCalledOnce())
  const emulator = mocks.instances[0]
  expect(emulator.options.fontSize).toBe(15)
  expect(emulator.options.disableStdin).toBe(true)
  emulator.data('not a command')
  expect(transport.write).not.toHaveBeenCalled()
  emulator.data('\x1b[1;1R')
  await waitFor(() => expect(transport.write).toHaveBeenCalledWith('one', '\x1b[1;1R'))
  expect(emulator.keyHandler({ metaKey: true, key: '+' })).toBe(false)
  expect(emulator.keyHandler({ ctrlKey: true, key: 'c' })).toBe(true)
  view.rerender(<TerminalView {...props} info={{ ...props.info, state: 'exited', mode: 'direct' }} />)
  expect(mocks.instances).toHaveLength(1)
  expect(emulator.dispose).not.toHaveBeenCalled()
  expect(emulator.options.disableStdin).toBe(true)
  emulator.data('ignored')
  expect(transport.write).toHaveBeenCalledTimes(1)
})
