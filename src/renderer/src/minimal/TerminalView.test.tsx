it('offers clipboard actions without sending a command-mode output paste to the shell', async () => {
  const { transport } = setup()
  await waitFor(() => expect(transport.attach).toHaveBeenCalled())
  const editor = screen.getByLabelText('Terminal command') as HTMLTextAreaElement
  fireEvent.change(editor, { target: { value: 'echo old' } }); editor.setSelectionRange(5, 8)
  vi.mocked(transport.pasteText).mockResolvedValueOnce('new')
  fireEvent.contextMenu(editor, { clientX: 30, clientY: 30 })
  fireEvent.click(screen.getByRole('menuitem', { name: 'Copy' }))
  expect(transport.copyText).toHaveBeenCalledWith('old')
  fireEvent.contextMenu(editor)
  fireEvent.click(screen.getByRole('menuitem', { name: 'Paste' }))
  await waitFor(() => expect(editor.value).toBe('echo new'))
  fireEvent.contextMenu(screen.getByLabelText('Terminal output'))
  expect((screen.getByRole('menuitem', { name: 'Paste' }) as HTMLButtonElement).disabled).toBe(true)
  expect(transport.write).not.toHaveBeenCalled()
})
