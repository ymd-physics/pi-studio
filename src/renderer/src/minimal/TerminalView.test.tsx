it('Ctrl-U kills only the current line prefix and invalidates pending completion', async () => {
  const { transport } = setup()
  const editor = screen.getByLabelText('Terminal command') as HTMLTextAreaElement
  fireEvent.change(editor, { target: { value: 'first\nhello tail' } })
  editor.setSelectionRange(11, 11)
  fireEvent.keyDown(editor, { key: 'u', ctrlKey: true })
  expect(editor.value).toBe('first\n tail')
  expect(editor.selectionStart).toBe(6)
  fireEvent.change(editor, { target: { value: 'clear me' } })
  let resolve!: (value: Awaited<ReturnType<TerminalTransport['complete']>>) => void
  vi.mocked(transport.complete).mockImplementationOnce(() => new Promise(r => { resolve = r }))
  fireEvent.keyDown(editor, { key: 'Tab' })
  fireEvent.keyDown(editor, { key: 'u', ctrlKey: true })
  expect(editor.value).toBe('')
  await act(async () => resolve({ buffer: 'stale', cursor: 5, options: [{ buffer: 'stale', cursor: 5 }] }))
  expect(editor.value).toBe('')
  expect(screen.queryByRole('listbox')).toBeNull()
  expect(transport.submit).not.toHaveBeenCalled()
  expect(transport.write).not.toHaveBeenCalled()
})
