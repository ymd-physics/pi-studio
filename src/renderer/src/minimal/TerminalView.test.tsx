it('cancels a pending submission with Ctrl-C without turning it into raw input', async () => {
  const { transport } = setup()
  let reject!: (error: Error) => void
  vi.mocked(transport.submit).mockImplementationOnce(() => new Promise((_, fail) => { reject = fail }))
  const editor = screen.getByLabelText('Terminal command')
  fireEvent.change(editor, { target: { value: 'do-not-run' } })
  fireEvent.keyDown(editor, { key: 'Enter' })
  fireEvent.keyDown(editor, { key: 'c', ctrlKey: true })
  expect(transport.interrupt).toHaveBeenCalledWith('one')
  expect(transport.write).not.toHaveBeenCalled()
  expect(editor).toHaveProperty('value', '')
  await act(async () => reject(new Error('Terminal submission cancelled')))
  expect(screen.queryByRole('alert')).toBeNull()
})
