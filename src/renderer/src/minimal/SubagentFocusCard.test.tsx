// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import type { SubagentCard, SubagentStatus } from '../../../../packages/shared/subagents'
import { SubagentFocusCard } from './SubagentFocusCard'

const agent = (id: string, extra: Partial<SubagentCard> = {}): SubagentCard => ({ id, name: id, state: 'running', startedAt: 0, ...extra })
const status = (...agents: SubagentCard[]): SubagentStatus => ({ availability: 'available', agents, updatedAt: Date.now() })
const advance = (ms: number) => act(() => vi.advanceTimersByTime(ms))
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(60_000) })
afterEach(() => { cleanup(); vi.useRealTimers() })

it('links attention only on user action and suppresses stale-status navigation', () => {
  const snapshot = status(agent('scout'), agent('reviewer', { state: 'waiting' }))
  const requestForAgent = (item: SubagentCard) => item.id === 'reviewer' ? 'request-1' : undefined
  const onRequest = vi.fn()
  const view = render(<SubagentFocusCard active status={snapshot} requestForAgent={requestForAgent} onRequest={onRequest} />)
  expect(onRequest).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: '1 needs attention' }))
  expect(onRequest).toHaveBeenCalledWith('request-1')
  expect(screen.getByRole('button', { name: 'View recorded request ↑' })).toBeTruthy()
  onRequest.mockClear()
  view.rerender(<SubagentFocusCard active status={{ ...snapshot, error: 'disconnected' }} requestForAgent={requestForAgent} onRequest={onRequest} />)
  expect(screen.queryByRole('button', { name: 'View recorded request ↑' })).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: '1 needs attention' }))
  expect(onRequest).not.toHaveBeenCalled()
})
it('expires successful entries at endedAt + 10s and freezes their elapsed clock', () => {
  const { rerender } = render(<SubagentFocusCard active status={status(agent('worker', { state: 'complete', endedAt: 58_000 }))} />)
  expect(screen.getByText('0m 58s')).toBeTruthy()
  advance(7_000)
  rerender(<SubagentFocusCard active status={status(agent('worker', { state: 'complete', endedAt: 59_000, activity: 'refreshed' }))} />)
  expect(screen.getByText('0m 58s')).toBeTruthy()
  advance(1_000)
  expect(screen.queryByRole('region')).toBeNull()
  expect(vi.getTimerCount()).toBe(0)
})

it('uses first observed completion without restarting on updates, paging or hide/show', () => {
  const done = agent('__proto__', { state: 'complete' })
  const running = agent('other')
  const { rerender } = render(<SubagentFocusCard active status={status(done, running)} />)
  expect(screen.getByText('1m 00s')).toBeTruthy()
  advance(3_000)
  fireEvent.click(screen.getByRole('button', { name: 'Next agent' }))
  rerender(<SubagentFocusCard active={false} status={status({ ...done, activity: 'new' }, running)} />)
  expect(vi.getTimerCount()).toBe(0)
  advance(4_000)
  rerender(<SubagentFocusCard active status={status(done, running)} />)
  fireEvent.click(screen.getByRole('button', { name: 'Previous agent' }))
  expect(screen.getByText('1m 00s')).toBeTruthy()
  advance(3_000)
  expect(screen.queryByText('__proto__')).toBeNull()
  expect(screen.getByText('other')).toBeTruthy()
})

it('resumes elapsed time correctly without background timers and immediately drops expired completion', () => {
  const running = agent('running')
  const done = agent('done', { state: 'complete' })
  const { rerender } = render(<SubagentFocusCard active status={status(running, done)} />)
  rerender(<SubagentFocusCard active={false} status={status(running, done)} />)
  expect(vi.getTimerCount()).toBe(0)
  advance(30_000)
  rerender(<SubagentFocusCard active status={status(running, done)} />)
  expect(screen.getByText('1m 30s')).toBeTruthy()
  expect(screen.getByText('1 / 1')).toBeTruthy()
})

it('manually pages many entries, preserves identity across reordering and cycles offpage attention', () => {
  const agents = Array.from({ length: 40 }, (_, i) => agent(`agent-${i}`, { state: i === 33 ? 'waiting' : i === 38 ? 'failed' : 'running' }))
  const { rerender, container } = render(<SubagentFocusCard active status={status(...agents)} />)
  expect(screen.getByText('38 running · 0 queued · 40 total')).toBeTruthy()
  for (let i = 0; i < 20; i++) fireEvent.click(screen.getByRole('button', { name: 'Next agent' }))
  expect(screen.getByText('agent-20')).toBeTruthy()
  expect(container.querySelectorAll('article')).toHaveLength(1)
  advance(5_000)
  expect(screen.getByText('agent-20')).toBeTruthy()
  rerender(<SubagentFocusCard active status={status(...agents.toReversed())} />)
  expect(screen.getByText('agent-20')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: '2 needs attention' }))
  expect(screen.getByText('agent-38')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: '2 needs attention' }))
  expect(screen.getByText('agent-33')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: '2 needs attention' }))
  expect(screen.getByText('agent-38')).toBeTruthy()
})

it('retains waiting, failed, paused and stopped entries without auto-dismissal', () => {
  const agents = (['waiting', 'failed', 'paused', 'stopped', 'queued'] as const).map(state => agent(state, { state }))
  render(<SubagentFocusCard active status={status(...agents)} />)
  expect(vi.getTimerCount()).toBe(0)
  advance(60_000)
  expect(screen.getByText('0 running · 1 queued · 5 total')).toBeTruthy()
  for (let i = 0; i < 3; i++) fireEvent.click(screen.getByRole('button', { name: 'Next agent' }))
  expect(screen.getByText('Stopped')).toBeTruthy()
  expect(screen.getByText('1m 00s')).toBeTruthy()
})

it('starts a fresh completion interval when an unknown child later reports success', () => {
  const { rerender } = render(<SubagentFocusCard active status={status(agent('worker', { state: 'unknown', endedAt: 59_000 }))} />)
  advance(20_000)
  rerender(<SubagentFocusCard active status={status(agent('worker', { state: 'complete', endedAt: 80_000 }))} />)
  expect(screen.getByText('Complete')).toBeTruthy()
  expect(screen.getByText('1m 20s')).toBeTruthy()
  advance(9_000)
  expect(screen.getByText('Complete')).toBeTruthy()
  advance(1_000)
  expect(screen.queryByRole('region')).toBeNull()
})
it('hides absent/unavailable plugins, but labels errors after known data as stale', () => {
  const { rerender } = render(<SubagentFocusCard active status={undefined} />)
  expect(screen.queryByRole('region')).toBeNull()
  rerender(<SubagentFocusCard active status={{ availability: 'unavailable', agents: [], updatedAt: 0, error: 'offline' }} />)
  expect(screen.queryByRole('region')).toBeNull()
  rerender(<SubagentFocusCard active status={status(agent('known'))} />)
  rerender(<SubagentFocusCard active status={{ availability: 'unavailable', agents: [], updatedAt: 0, error: 'offline' }} />)
  expect(screen.getByText('known')).toBeTruthy()
  expect(screen.getByRole('status').textContent).toContain('Stale subagent status — offline')
  rerender(<SubagentFocusCard active status={{ availability: 'unavailable', agents: [], updatedAt: 0 }} />)
  expect(screen.queryByRole('region')).toBeNull()
})

it('does not resurrect expired completions after an unavailable snapshot and cleans up timers', () => {
  const done = agent('done', { state: 'complete', endedAt: 50_000 })
  const { rerender, unmount } = render(<SubagentFocusCard active status={status(done)} />)
  expect(screen.queryByRole('region')).toBeNull()
  expect(vi.getTimerCount()).toBe(0)
  rerender(<SubagentFocusCard active status={undefined} />)
  advance(2_000)
  rerender(<SubagentFocusCard active status={status(done, agent('live'))} />)
  expect(screen.getByText('1 / 1')).toBeTruthy()
  expect(vi.getTimerCount()).toBe(1)
  unmount()
  expect(vi.getTimerCount()).toBe(0)
})

it('renders hostile long task strings as bounded plain text and reports missing fields honestly', () => {
  const task = '<img src=x onerror=alert(1)>' + 'x'.repeat(20_000)
  const { container } = render(<SubagentFocusCard active status={status(agent('worker', { task, startedAt: undefined }))} />)
  const text = screen.getByText(task)
  expect(text.title).toBe(task)
  expect(text.className).toBe('subagent-focus-task')
  expect(container.querySelector('img')).toBeNull()
  for (const field of ['Model', 'Thinking', 'Activity', 'Time']) expect(screen.getByText(`${field} unavailable`)).toBeTruthy()
})
